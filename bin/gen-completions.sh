#!/usr/bin/env bash
#
# gen-completions.sh - generate the zsh completion (_ldx) for the ldx CLI.
#
# Sources of truth, scanned at generation time (no hand-maintained list):
#   - top-level commands: the "# ldx-help: <group> <text>" tag in each
#     bin/commands/ldx-* file (same metadata 'ldx help' renders)
#   - subcommands: the "Commands:" block of each command's help output
#     (name + one-line description; continuation lines and "Flags:" runs
#     are folded into the description)
#
# Usage:
#   bin/gen-completions.sh             print the _ldx file to stdout
#   bin/gen-completions.sh --install   write it where zsh will find it:
#                                      brew's site-functions when brew is
#                                      present, else ~/.zfunc (with an
#                                      fpath hint). Run by 'ldx install' and
#                                      'ldx completions' (and, through
#                                      post_install, by 'brew install/upgrade').
#
set -euo pipefail

_LDX_SELF="$(realpath "${BASH_SOURCE[0]}")"
LDX_HOME="$(cd "$(dirname "${_LDX_SELF}")/.." && pwd)"
COMMAND_DIR="${LDX_HOME}/bin/commands"

# zsh single-quote escaping for _describe arrays: backslash, then the
# quote-backslash-quote-quote-quote idiom (the only way to embed a quote
# inside zsh single quotes).
zq() {
    local s="$1"
    s="${s//\\/\\\\}"          # backslash -> double backslash
    s="${s//\'/\'\\\'\'}"      # quote -> quote-backslash-quote-quote
    printf '%s' "$s"
}

emit_array() {
    # $1 = array name, rest of stdin = "name<TAB>desc" lines (cont lines fold)
    local array="$1" line name desc entry
    local -a entries=()
    local pending_name="" pending_desc=""
    flush() {
        [ -n "$pending_name" ] || return 0
        # fold "Flags: ..." runs out of the description
        local d="${pending_desc%% Flags:*}"
        entries+=("$(printf "    '%s:%s'" "$(zq "$pending_name")" "$(zq "$d")")")
        pending_name="" pending_desc=""
    }
    while IFS=$'\t' read -r name desc extra; do
        if [ "$name" = "cont" ]; then
            pending_desc="${pending_desc} ${desc}"
            continue
        fi
        flush
        pending_name="$name"
        pending_desc="$desc"
    done
    flush
    printf '%s=(\n' "$array"
    [ ${#entries[@]} -gt 0 ] && printf '%s\n' "${entries[@]}"
    printf ')\n\n'
}

generate() {
    local file name tag desc

    echo "#compdef ldx"
    echo "# Generated by bin/gen-completions.sh (ldx completions) - do not edit."
    echo "# Regenerate after adding a command or changing its 'Commands:' help."
    echo ""

    # --- top-level commands ------------------------------------------------
    local -a top=()
    top+=("'install:Symlink ldx into a local bin directory'")
    top+=("'completions:Regenerate the zsh completion (_ldx)'")
    top+=("'help:Show usage'")
    top+=("'--version:Print version'")
    for file in "${COMMAND_DIR}"/ldx-*; do
        [ -x "$file" ] || continue
        tag="$(grep -m1 '^[# ]*# ldx-help:' "$file" 2>/dev/null | sed 's/.*# ldx-help: //' || true)"
        [ -n "$tag" ] || continue
        name="$(basename "$file")"
        desc="${tag#* }"  # strip the leading group key
        top+=("$(printf "'%s:%s'" "$(zq "${name#ldx-}")" "$(zq "$desc")")")
    done
    echo "_ldx_cmds=("
    printf '%s\n' "${top[@]}" | sed 's/^/    /'
    echo ")"
    echo ""

    # --- per-command subcommands -------------------------------------------
    for file in "${COMMAND_DIR}"/ldx-*; do
        [ -x "$file" ] || continue
        name="$(basename "$file")"
        name="${name#ldx-}"
        case "$name" in
            [a-z0-9-]*) ;;
            *) continue ;;
        esac
        local array="_ldx_cmd_${name//-/_}"
        printf '# %s\n' "$name"
        "$file" help 2>/dev/null \
            | command_subcommands_from_stdin \
            | emit_array "$array" || true
    done

    # --- dispatcher ---------------------------------------------------------
    cat <<'ZSH'
_ldx() {
    local curcontext="$curcontext" state ret=1
    typeset -A opt_args

    _arguments -C \
        '1: :->cmd' \
        '*:: :->args' && ret=0

    case $state in
        cmd)
            _describe -t commands 'ldx command' _ldx_cmds && ret=0
            ;;
        args)
            local -a subs
            case $words[1] in
                install)
                    _arguments \
                        '--dir[Target directory]:dir:_files -/' \
                        '--link[Symlink mode (default)]' \
                        '(- --copy)--mode[Install mode]:mode:(link symlink)' && ret=0
                    ;;
                k8s)
                    subs=($_ldx_cmd_k8s)
                    ;;
                *)
                    local fn="_ldx_cmd_${${words[1]}//-/_}"
                    subs=(${(P)fn})
                    ;;
            esac
            if (( ${#subs} > 0 )); then
                _describe -t subcommands "$words[1] subcommand" subs && ret=0
            fi
            _message 'ldx option' && ret=0
            ;;
    esac
    return ret
}

_ldx "$@"
ZSH
}

# command_subcommands helper reads from stdin (the per-command help).
command_subcommands_from_stdin() {
    awk '
        /^Commands:$/ { inblock = 1; next }
        inblock && /^[[:space:]]*$/ { exit }
        inblock && /^  [a-z][a-z0-9-]*,?([[:space:]]|$)/ {
            name = $1; sub(/,$/, "", name)
            rest = $0
            sub(/^  [^ ]+[[:space:]]*/, "", rest)
            alias = ""
            if ($1 ~ /,$/ && $2 ~ /^[a-z][a-z0-9-]*$/ && NF > 2) {
                alias = $2
                sub(/^ *[^ ]+[[:space:]]*/, "", rest)
            }
            gsub(/[[:space:]]+/, " ", rest)
            gsub(/^[[:space:]]+|[[:space:]]+$/, "", rest)
            print name "\t" rest
            if (alias != "") print alias "\t(alias of " name ")"
            current = name
            next
        }
        inblock && /^   +/ && current != "" {
            line = $0
            gsub(/^[[:space:]]+/, "", line)
            gsub(/[[:space:]]+/, " ", line)
            printf "cont\t%s\n", line
            next
        }
    '
}

install_target() {
    local brew_prefix site
    if command -v brew &>/dev/null && brew_prefix="$(brew --prefix 2>/dev/null)" \
        && [ -d "${brew_prefix}/share/zsh/site-functions" ]; then
        printf '%s\n' "${brew_prefix}/share/zsh/site-functions"
        return 0
    fi
    printf '%s\n' "${HOME}/.zfunc"
}

main() {
    if [ "${1:-}" = "--install" ]; then
        local dir
        dir="$(install_target)"
        mkdir -p "$dir"
        local out="${dir}/_ldx"
        local tmp="${out}.tmp.$$"
        generate >"$tmp"
        mv -f "$tmp" "$out"
        echo "zsh completion written to ${out}" >&2
        case "$dir" in
            *site-functions)
                echo "  (Homebrew site-functions: already on your fpath.)" >&2
                echo "  Needs the zsh completion system initialized in ~/.zshrc:" >&2
                echo "    autoload -Uz compinit && compinit" >&2
                ;;
            *)
                echo "  Add to ~/.zshrc if not set already:" >&2
                echo "    fpath=(~/.zfunc \$fpath)" >&2
                echo "    autoload -Uz compinit && compinit" >&2
                ;;
        esac
        return 0
    fi
    generate
}

main "$@"
